import { ChangeDetectionStrategy, Component, computed, effect, inject, input, OnInit, signal } from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import {
  lucideBike,
  lucideDownload,
  lucideSearch,
  lucideZap,
} from '@ng-icons/lucide';
import { HlmNativeSelectImports } from '@spartan-ng/helm/native-select';
import { HlmSwitchImports } from '@spartan-ng/helm/switch';
import { RouteService } from '../../services/route-service';
import { firstValueFrom } from 'rxjs';
import { toast } from '@spartan-ng/brain/sonner';
import { RouteAiResponse } from '../../interfaces/route-ai.interface';
import type { LatLngTuple } from 'leaflet';
import { DatePipe } from '@angular/common';
import { RouteMap, RouteMapMarker } from '../ai-route-details/route-map/route-map';
import { lucideDelete } from "@ng-icons/lucide";
import { HlmButtonImports } from "@spartan-ng/helm/button";
import { lucideNavigationOff } from "@ng-icons/lucide";
import { formatTime } from '../../../../shared/utils';
import { lucideBookmark } from "@ng-icons/lucide";


type AsphaltFilter = 'all' | 'asphalt' | 'mixed';
type SortOrder = 'recent' | 'oldest' | 'distance';


/** Historial de rutas generadas por el usuario con buscador, filtros y paginación. */
@Component({
  selector: 'app-ai-user-route',
  imports: [NgIcon, HlmNativeSelectImports, HlmSwitchImports, DatePipe, HlmButtonImports, RouteMap],
  templateUrl: './ai-user-route.html',
  changeDetection: ChangeDetectionStrategy.OnPush,
  providers: [provideIcons({ lucideBike, lucideDownload, lucideSearch, lucideZap, lucideDelete, lucideNavigationOff, lucideBookmark})],
})
export class AiUserRoute implements OnInit {

  /** Indica si se ha generado una nueva ruta. */
  public newRoute = input<boolean>(false)

  /** Total de rutas guardadas en el historial. */
  protected readonly totalGenerations = 0;
  /** Número total de páginas del historial. */
  protected readonly pageCount = 0;

  /** Texto introducido en el buscador. */
  protected readonly searchTerm = signal('');
  /** Filtro por tipo de asfalto. */
  protected readonly asphaltFilter = signal<AsphaltFilter>('all');
  /** Orden de los resultados. */
  protected readonly sortOrder = signal<SortOrder>('recent');
  /** Indica si solo se muestran rutas con track GPX disponible. */
  protected readonly onlyGpx = signal(false);
  /** Página actual del historial. */
  protected readonly page = signal(1);
  /** Carga de rutas generadas por el usuario */
  public userRoutes = signal<RouteAiResponse[]>([])

  private _routeService = inject(RouteService)

  ngOnInit(): void {
    this.getRoutesAiUser()
  }

  constructor(){
    effect(() => {
      if(this.newRoute()){
        this.getRoutesAiUser()
      }
    })
  }

  /** Fetch routes generated by AI and request from the user authenticated. */
  private async getRoutesAiUser(){
    try {
      const response = await firstValueFrom(this._routeService.getRoutesAiUser())
      this.userRoutes.set(response)
      console.log(response)
    } catch (error) {
      toast.error("No se han podido recuperar las rutas generadas con IA.")
    }
  }

  public formatCoords(coords: RouteAiResponse['coords']): LatLngTuple[] {
    return coords.map(({ lat, lon }) => [lat, lon]);
  } 

  public getTypeOfRoute( route_type : string) : string{
    
    let type_text = ''
    switch(route_type){
      case 'relaxed':
        type_text = 'Relajada'
        break;
      case 'circular':
        type_text = 'Circular'
        break
      case 'fast':
        type_text = 'Rápida y fluida'
        break
      default:
        type_text = route_type
        break
    }
    return type_text
  }

  public formatMarkers(coords : [] | {}) : RouteMapMarker[]{
    let markers : RouteMapMarker[] = []
    
    if(Array.isArray(coords) && coords.length > 0){
      for(const coord of coords){
        markers.push({
          position: [coord.lat, coord.lon],
          label: coord.name
        })
      }
    }
    return markers
  }

  public getTotalTime( duration: number){
    return formatTime(duration)
  }
}
